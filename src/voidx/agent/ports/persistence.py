    async def archive_goal_generation(self, generation: str) -> Any: ...
    async def cleanup_goal_generation(self, generation: str) -> Any: ...
    async def list_goal_generations(self, main_session_id: str) -> list[Any]: ...
    async def prepare_goal_generation_cleanup(self, generation: str, *, reason: str) -> Any: ...
    async def prepare_orphan_goal_generation_cleanups(self) -> list[str]: ...
    async def list_goal_cleanup_tombstones(self) -> list[dict[str, Any]]: ...
    async def reconcile_goal_cleanup(self, generation: str) -> Any: ...
    async def ensure_goal_phase_outbox(self, generation: str) -> Any | None: ...
    async def acquire_goal_generation_lease(self, generation: str, lease_owner: str, *, lease_seconds: float) -> bool: ...
    async def renew_goal_generation_lease(self, generation: str, lease_owner: str, *, lease_seconds: float) -> bool: ...
    async def release_goal_generation_lease(self, generation: str, lease_owner: str) -> bool: ...
    async def get_goal_generation_lease(self, generation: str) -> dict[str, Any] | None: ...
    async def ensure_session(self, session_id: str, workspace: str, *, profile: str = "coding", title: str = "Loop session", root_session_id: str | None = None, profile_snapshot: Any | None = None) -> None: ...
    async def get_session(self, session_id: str) -> Any | None: ...



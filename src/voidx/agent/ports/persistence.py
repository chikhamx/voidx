    async def commit_goal_needs_resume(self, *, attempt_id: str, phase: str, reason: str, lease_owner: str, fencing_token: int, guidance_delivery_id: str = "") -> Any: ...
    async def get_goal_protocol(self, protocol_id: str) -> Any | None: ...
    async def list_goal_protocols(self, generation: str) -> list[Any]: ...
    async def project_goal_protocol(self, protocol_id: str) -> Any: ...
    async def get_goal_generation(self, generation: str) -> Any | None: ...
    async def get_goal_runtime_failure(self, generation: str) -> Any | None: ...
    async def fail_goal_generation(self, failure: Any) -> Any: ...
    async def list_goal_public_summaries(self, main_session_id: str) -> list[dict[str, Any]]: ...
    async def list_pending_goal_public_summaries(self, *, main_session_id: str = "", generation: str = "") -> list[dict[str, Any]]: ...
    async def deliver_goal_public_summary(self, summary_id: str) -> bool: ...
